const fs = require('fs');
const path = require('path');
const pc = require('picocolors');
const { loadState, loadContext, isInitialized } = require('./state');
const { getTemplate } = require('./promptEngine');
const logger = require('./logger');

const RULES_CONFIG_FILE = path.join('.buildwithai', 'rules.config.json');

// Managed block markers. Everything outside this block is treated as the
// developer's own custom instructions and is never modified or removed.
const RULES_BLOCK_START = '<!-- build-with-ai:rules start -->';
const RULES_BLOCK_END = '<!-- build-with-ai:rules end -->';

const CURSOR_MDC_FRONTMATTER = [
  '---',
  'description: Project decisions and conventions synced from build-with-ai context.json',
  'globs:',
  '  - "**/*"',
  '---',
  ''
].join('\n');

// Rule files to sync, relative to the project root. The .mdc target needs
// Cursor's frontmatter header so it is picked up as a project rule.
const RULE_TARGETS = [
  { file: '.cursorrules' },
  { file: path.join('.cursor', 'rules', 'project-decisions.mdc'), frontmatter: CURSOR_MDC_FRONTMATTER },
  { file: '.windsurfrules' },
  { file: 'CLAUDE.md' },
  { file: path.join('.github', 'copilot-instructions.md') }
];

function formatValue(value) {
  if (value === null || value === undefined) return '';
  if (typeof value === 'object') return JSON.stringify(value);
  return String(value);
}

function titleCase(key) {
  return key
    .replace(/([A-Z])/g, ' $1')
    .replace(/^./, (str) => str.toUpperCase())
    .trim();
}

function loadRulesConfig(cwd) {
  const configPath = path.join(cwd, RULES_CONFIG_FILE);
  if (!fs.existsSync(configPath)) return {};

  let config;
  try {
    config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
  } catch (error) {
    logger.error(
      `Unable to read ${configPath}. Check file permissions and restore valid JSON. Error: ${error.message}`
    );
    return null;
  }

  if (!config || typeof config !== 'object' || Array.isArray(config)) {
    logger.error(`Invalid rules configuration in ${configPath}. Expected a JSON object.`);
    return null;
  }

  for (const key of ['includeKeys', 'excludeKeys']) {
    if (
      config[key] !== undefined &&
      (!Array.isArray(config[key]) || config[key].some((item) => typeof item !== 'string'))
    ) {
      logger.error(`Invalid rules configuration in ${configPath}. ${key} must be an array of decision-key strings.`);
      return null;
    }
  }

  return config;
}

function isWithinDecisionPath(path, parentPath) {
  return path === parentPath || path.startsWith(`${parentPath}.`);
}

function filterDecisionValue(value, decisionPath, includeKeys, excludeKeys, includeEnabled) {
  if (excludeKeys.some((key) => isWithinDecisionPath(decisionPath, key))) return undefined;

  if (value && typeof value === 'object' && !Array.isArray(value)) {
    const filtered = {};
    for (const [key, nestedValue] of Object.entries(value)) {
      const nestedPath = `${decisionPath}.${key}`;
      const filteredValue = filterDecisionValue(nestedValue, nestedPath, includeKeys, excludeKeys, includeEnabled);
      if (filteredValue !== undefined) filtered[key] = filteredValue;
    }
    if (Object.keys(filtered).length > 0) return filtered;
    if (
      Object.keys(value).length === 0 &&
      (!includeEnabled || includeKeys.some((key) => isWithinDecisionPath(key, decisionPath)))
    ) {
      return value;
    }
    return undefined;
  }

  if (includeEnabled && !includeKeys.some((key) => isWithinDecisionPath(decisionPath, key))) return undefined;
  return value;
}

function filterDecisions(decisions, config = {}) {
  const includeKeys = config.includeKeys || [];
  const excludeKeys = config.excludeKeys || [];
  const includeEnabled = Array.isArray(config.includeKeys);
  if (!includeEnabled && excludeKeys.length === 0) return decisions;

  const filtered = {};
  for (const [key, value] of Object.entries(decisions)) {
    const decisionPath = `decisions.${key}`;
    const filteredValue = filterDecisionValue(value, decisionPath, includeKeys, excludeKeys, includeEnabled);
    if (filteredValue !== undefined) filtered[key] = filteredValue;
  }
  return filtered;
}

/**
 * Generates the managed markdown body from context.json + state.
 * @param {object} context
 * @param {object} state
 * @param {string} [activePhase] Human-readable "Step N — Title (Phase)" string.
 * @param {object} [rulesConfig={}]
 * @returns {string}
 */
function generateRulesContent(context, state = {}, activePhase = '', rulesConfig = {}) {
  const p = context.project || {};
  const d = filterDecisions(context.decisions || {}, rulesConfig);
  const projectName = state.projectName || p.name || 'My Project';

  const lines = [];
  lines.push(`# ${projectName} — Project Rules`);
  lines.push('');
  lines.push(
    '_Generated by `build-with-ai export --rules` from `.buildwithai/context.json`. ' +
      'This block is managed automatically — update decisions with `build-with-ai set <key> <value>` and re-run. ' +
      'Your own instructions outside the managed block are preserved._'
  );
  lines.push('');

  lines.push('## Project overview');
  lines.push(formatValue(p.idea || state.projectIdea || 'Built with AI guided workflows.'));
  lines.push('');

  lines.push('## Tech stack');
  lines.push(`- Frontend: ${formatValue(d.frontendStack || d.framework || 'Not decided yet')}`);
  lines.push(`- Backend: ${formatValue(d.backendStack || d.runtime || 'Not decided yet')}`);
  lines.push(`- Database: ${formatValue(d.database || 'Not decided yet')}`);
  // Templates write auth under different keys; fall back through them so
  // the tech stack summary never drops the authentication decision (#195).
  const auth = d.authStrategy || d.authProvider || d.authImplementation || d.authModule || d.auth;
  if (auth) lines.push(`- Auth: ${formatValue(auth)}`);
  if (d.deploymentPlatform) lines.push(`- Hosting: ${formatValue(d.deploymentPlatform)}`);
  lines.push('');

  if (activePhase) {
    lines.push('## Active phase');
    lines.push(activePhase);
    lines.push('');
  }

  const decisionKeys = Object.keys(d).filter(
    (key) =>
      ![
        'frontendStack',
        'framework',
        'backendStack',
        'runtime',
        'database',
        'authStrategy',
        'authProvider',
        'authImplementation',
        'authModule',
        'auth',
        'deploymentPlatform'
      ].includes(key)
  );
  if (decisionKeys.length > 0) {
    lines.push('## Decisions');
    for (const key of decisionKeys) {
      const value = formatValue(d[key]);
      if (value) lines.push(`- **${titleCase(key)}:** ${value}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

/**
 * Merges generated content into an existing rule file without clobbering
 * custom instructions: an existing managed block is replaced in place,
 * and when no managed block exists the custom content is kept and the
 * managed block is appended.
 * @param {string|null} existing
 * @param {string} generated
 * @returns {string}
 */
function mergeRulesFile(existing, generated) {
  const block = `${RULES_BLOCK_START}\n${generated.trim()}\n${RULES_BLOCK_END}`;
  if (existing === null || existing === undefined) return `${block}\n`;
  const startIdx = existing.indexOf(RULES_BLOCK_START);
  const endIdx = existing.indexOf(RULES_BLOCK_END);
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    return existing.slice(0, startIdx) + block + existing.slice(endIdx + RULES_BLOCK_END.length);
  }
  const trimmed = existing.replace(/\s+$/, '');
  return trimmed ? `${trimmed}\n\n${block}\n` : `${block}\n`;
}

/**
 * Describes the rule files that would be generated.
 * @param {string} [cwd=process.cwd()]
 * @returns {string[]}
 */
function getRuleFilePaths(cwd = process.cwd()) {
  return RULE_TARGETS.map((target) => path.join(cwd, target.file));
}

/**
 * Syncs editor rule files from context.json.
 * @param {string} [cwd=process.cwd()]
 * @param {object} [options={}]
 * @param {boolean} [options.dryRun=false] - List target paths without writing.
 * @returns {Promise<false|string[]|undefined>} False on failure, else written/listed paths.
 */
async function runRulesExport(cwd = process.cwd(), options = {}) {
  const { dryRun = false } = options;

  if (!isInitialized(cwd)) {
    logger.error('No active project found. Run `npx build-with-ai init` first.');
    return false;
  }
  const state = loadState(cwd);
  if (!state) {
    logger.error(
      'Cannot export rule files without valid project state. Restore .buildwithai/state.json from a backup.'
    );
    return false;
  }

  const context = loadContext(cwd);
  const rulesConfig = loadRulesConfig(cwd);
  if (!rulesConfig) return false;

  // Current active phase: "Step N — Title (Phase)" when a template is loaded.
  let activePhase = '';
  const template = getTemplate(state.templateId, cwd);
  if (template && template.steps) {
    const currentStepNum = state.currentStep || 1;
    if (currentStepNum <= template.steps.length) {
      const step = template.steps[currentStepNum - 1];
      activePhase = `Step ${currentStepNum}/${template.steps.length} — ${step.title} (${step.phase || 'General'})`;
    } else {
      activePhase = `All ${template.steps.length} steps completed — project finished.`;
    }
  }

  const generated = generateRulesContent(context, state, activePhase, rulesConfig);
  const written = [];

  if (dryRun) {
    console.log();
    console.log(pc.bold(pc.cyan('Dry run — the following rule files would be synced:')));
    for (const target of RULE_TARGETS) {
      console.log(`  ${pc.dim('•')} ${target.file}`);
    }
    console.log();
    console.log(pc.dim('No files were created or changed.'));
    console.log();
    return getRuleFilePaths(cwd);
  }

  for (const target of RULE_TARGETS) {
    const filePath = path.join(cwd, target.file);
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    let existing = null;
    if (fs.existsSync(filePath)) {
      existing = fs.readFileSync(filePath, 'utf8');
    } else if (target.frontmatter) {
      existing = target.frontmatter;
    }
    const merged = mergeRulesFile(existing, generated);
    fs.writeFileSync(filePath, merged, 'utf8');
    written.push(filePath);
  }

  console.log();
  logger.success('Editor rule files synced from context.json!');
  console.log();
  for (const filePath of written) {
    console.log(`  ${pc.green('✔')} ${pc.bold(path.relative(cwd, filePath))}`);
  }
  console.log();
  console.log(pc.dim('Custom instructions outside the managed block were preserved.'));
  console.log();

  return written;
}

module.exports = {
  runRulesExport,
  generateRulesContent,
  mergeRulesFile,
  getRuleFilePaths,
  RULE_TARGETS,
  RULES_BLOCK_START,
  RULES_BLOCK_END
};
